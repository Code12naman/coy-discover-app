import {
  Pool,
  type PoolClient,
  type QueryResult,
  type QueryResultRow,
} from "pg";

export interface AppDatabase {
  query<Row extends QueryResultRow = QueryResultRow>(
    text: string,
    values?: unknown[],
  ): Promise<QueryResult<Row>>;
  transaction<T>(callback: (database: AppDatabase) => Promise<T>): Promise<T>;
  close(): Promise<void>;
}

class PostgresDatabase implements AppDatabase {
  constructor(
    private readonly pool: Pool,
    private readonly client?: PoolClient,
  ) {}

  query<Row extends QueryResultRow = QueryResultRow>(
    text: string,
    values: unknown[] = [],
  ): Promise<QueryResult<Row>> {
    return (this.client ?? this.pool).query<Row>(text, values);
  }

  async transaction<T>(
    callback: (database: AppDatabase) => Promise<T>,
  ): Promise<T> {
    if (this.client) {
      throw new Error("Nested database transactions are not supported");
    }

    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");
      const result = await callback(new PostgresDatabase(this.pool, client));
      await client.query("COMMIT");
      return result;
    } catch (error) {
      await client.query("ROLLBACK");
      throw error;
    } finally {
      client.release();
    }
  }

  async close(): Promise<void> {
    if (!this.client) await this.pool.end();
  }
}

export function getDatabaseConnectionString(): string {
  const connectionString = [
    process.env.DATABASE_URL,
    process.env.POSTGRES_URL,
    process.env.POSTGRES_PRISMA_URL,
    process.env.POSTGRES_URL_NON_POOLING,
  ].find((value) => value?.trim());

  if (!connectionString) {
    throw new Error(
      "Configure DATABASE_URL (or POSTGRES_URL) with a persistent PostgreSQL connection string",
    );
  }

  return connectionString.trim();
}

export function createDatabase(
  connectionString = getDatabaseConnectionString(),
) {
  const pool = new Pool({
    connectionString,
    max: 1,
    idleTimeoutMillis: 10_000,
    connectionTimeoutMillis: 10_000,
  });
  return new PostgresDatabase(pool);
}

export async function initializeDatabase(db: AppDatabase): Promise<void> {
  await db.query(`
    CREATE TABLE IF NOT EXISTS profiles (
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL,
      age INTEGER NOT NULL CHECK (age BETWEEN 18 AND 30),
      photo_url TEXT NOT NULL,
      bio TEXT NOT NULL,
      city_or_college TEXT NOT NULL,
      interests JSONB NOT NULL
    )
  `);
  await db.query(`
    CREATE TABLE IF NOT EXISTS swipes (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      swiper_id TEXT NOT NULL,
      target_id TEXT NOT NULL,
      direction TEXT NOT NULL CHECK (direction IN ('like', 'pass')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (swiper_id, target_id)
    )
  `);
  await db.query(`
    CREATE TABLE IF NOT EXISTS matches (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      profile_id TEXT NOT NULL UNIQUE REFERENCES profiles(id),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);
  await db.query(
    "CREATE INDEX IF NOT EXISTS swipes_target_idx ON swipes(target_id)",
  );
  await db.query(
    "CREATE INDEX IF NOT EXISTS matches_created_at_idx ON matches(created_at)",
  );
}

export function createDatabaseFromPool(pool: Pool): AppDatabase {
  return new PostgresDatabase(pool);
}
